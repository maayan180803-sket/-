const rtlPara = (opts = {}) => ({
  bidirectional: true,
  alignment: AlignmentType.RIGHT,
  ...opts,
});

function H1(text) {
  return new Paragraph({
    ...rtlPara(),
    heading: HeadingLevel.HEADING_1,
    spacing: { before: 400, after: 200 },
    border: { bottom: { color: GOLD, space: 6, style: BorderStyle.SINGLE, size: 6 } },
    children: [new TextRun({ text, font: FONT, color: WINE, bold: true, size: 32, rightToLeft: true })],
  });
}
function H2(text) {
  return new Paragraph({
    ...rtlPara(),
    heading: HeadingLevel.HEADING_2,
    spacing: { before: 260, after: 140 },
    children: [new TextRun({ text, font: FONT, color: ROSE, bold: true, size: 26, rightToLeft: true })],
  });
}
function H3(text) {
  return new Paragraph({
    ...rtlPara(),
    spacing: { before: 180, after: 80 },
    children: [new TextRun({ text, font: FONT, color: WINE, bold: true, size: 22, rightToLeft: true })],
  });
}
function P(text, opts = {}) {
  return new Paragraph({
    ...rtlPara(),
    spacing: { after: 120 },
    children: [new TextRun({ text, font: FONT, color: INK, size: 22, rightToLeft: true, ...opts })],
  });
}
function Bullet(text) {
  return new Paragraph({
    ...rtlPara(),
    numbering: { reference: 'bullets', level: 0 },
    spacing: { after: 60 },
    children: [new TextRun({ text, font: FONT, color: INK, size: 22, rightToLeft: true })],
  });
}
function PMulti(text) {
  return text.split('\n').map((line) => P(line.trim().length ? line : ' '));
}
function Small(text) {
  return new Paragraph({
    ...rtlPara(),
    spacing: { after: 200 },
    children: [new TextRun({ text, font: FONT, color: '6B5F58', italics: true, size: 20, rightToLeft: true })],
  });
}
function pageBreakPara() {
  return new Paragraph({ children: [new TextRun({ text: '', break: 1 })], pageBreakBefore: true });
}

function cell(text, { header = false, width = 2000 } = {}) {
  return new TableCell({
    width: { size: width, type: WidthType.DXA },
    shading: header ? { type: ShadingType.CLEAR, color: 'auto', fill: ROSE } : undefined,
    children: [new Paragraph({
      ...rtlPara(),
      children: [new TextRun({
        text, font: FONT, size: 18, rightToLeft: true,
        color: header ? 'FFFFFF' : INK, bold: header,
      })],
    })],
  });
}

function calendarTable(rows, widths) {
  return new Table({
    width: { size: 9500, type: WidthType.DXA },
    columnWidths: widths,
    rows: rows.map((r, i) => new TableRow({
      children: r.map((c, ci) => cell(c, { header: i === 0, width: widths[ci] })),
    })),
  });
}

